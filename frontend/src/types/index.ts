/**
 * Shared domain types for ReturnWise.
 *
 * Money rule: amounts are DECIMAL STRINGS (e.g. "49.99"), never floats.
 * This matches how the backend will serialize Decimal values and avoids
 * floating-point errors in financial data. Format them for display only.
 */

export type CurrencyCode = "USD" | "EUR" | "GBP";

export type MoneyString = string;

/* ---------- Orders ---------- */

export type PaymentStatus =
  | "pending"
  | "captured"
  | "partially_refunded"
  | "refunded"
  | "failed";

export interface Customer {
  id: string;
  name: string;
  email: string;
}

export interface OrderItem {
  id: string;
  sku: string;
  name: string;
  quantity: number;
  unitPrice: MoneyString;
  /** Final-sale / non-returnable items fail the policy check. */
  returnable: boolean;
}

export interface Order {
  id: string;
  orderNumber: string;
  customer: Customer;
  items: OrderItem[];
  currency: CurrencyCode;
  total: MoneyString;
  /** Total already refunded across all returns. */
  refundedAmount: MoneyString;
  paymentStatus: PaymentStatus;
  /** Present only after a real PayPal capture. Demo data leaves this empty. */
  paypalCaptureId: string | null;
  /** ISO 8601 timestamps. */
  placedAt: string;
  deliveredAt: string | null;
}

/* ---------- Return requests ---------- */

export type ReturnStatus =
  | "submitted"
  | "under_review"
  | "approved"
  | "rejected"
  | "refund_pending"
  | "refunded"
  | "refund_failed";

export type ReturnReasonCategory =
  | "damaged"
  | "wrong_item"
  | "not_as_described"
  | "size_fit"
  | "changed_mind"
  | "late_delivery"
  | "other";

export interface ReturnLineItem {
  orderItemId: string;
  quantity: number;
}

export interface ReturnRequest {
  id: string;
  /** Human-friendly reference, e.g. "RET-1042". */
  reference: string;
  orderId: string;
  customer: Customer;
  status: ReturnStatus;
  items: ReturnLineItem[];
  /** Untrusted customer-written text. Always render as plain text. */
  customerComment: string;
  /** Amount the customer is asking to be refunded. */
  requestedAmount: MoneyString;
  currency: CurrencyCode;
  submittedAt: string;
  updatedAt: string;
  /** Set when the seller approves or rejects. */
  decisionNote: string | null;
}

/* ---------- Policy engine ---------- */

export type PolicyReasonCode =
  | "WITHIN_RETURN_WINDOW"
  | "RETURN_WINDOW_EXPIRED"
  | "PAYMENT_CAPTURED"
  | "PAYMENT_NOT_CAPTURED"
  | "ITEM_RETURNABLE"
  | "ITEM_NOT_RETURNABLE"
  | "QUANTITY_VALID"
  | "QUANTITY_EXCEEDS_ORDERED"
  | "AMOUNT_WITHIN_REFUNDABLE"
  | "AMOUNT_EXCEEDS_REFUNDABLE"
  | "NO_DUPLICATE_REQUEST"
  | "DUPLICATE_REQUEST";

export interface PolicyCheck {
  code: PolicyReasonCode;
  label: string;
  passed: boolean;
  /** Short explanation shown beside the check. */
  detail: string;
}

export interface PolicyEvaluation {
  returnId: string;
  eligible: boolean;
  checks: PolicyCheck[];
  evaluatedAt: string;
}

/* ---------- AI analysis ---------- */

/**
 * "ai"       - generated by Gemini through the backend.
 * "fallback" - deterministic rule-based output (no AI used).
 * "demo"     - static sample content used by the frontend demo mode.
 */
export type AnalysisSource = "ai" | "fallback" | "demo";

export type SuggestedAction =
  | "approve"
  | "reject"
  | "request_more_info"
  | "manual_review";

export interface AiAnalysis {
  returnId: string;
  source: AnalysisSource;
  category: ReturnReasonCategory;
  summary: string;
  keyPoints: string[];
  suggestedAction: SuggestedAction;
  rationale: string;
  /** 0 to 1. Advisory only; never used for payment decisions. */
  confidence: number;
  generatedAt: string;
}

/* ---------- Refund tracking ---------- */

export type RefundStepStatus = "complete" | "current" | "upcoming" | "failed";

export interface RefundTimelineStep {
  id: string;
  title: string;
  description: string;
  status: RefundStepStatus;
  /** ISO timestamp; null if the step has not happened. */
  occurredAt: string | null;
}

export type RefundStatus =
  | "not_started"
  | "pending"
  | "completed"
  | "failed";

export interface RefundRecord {
  returnId: string;
  status: RefundStatus;
  amount: MoneyString;
  currency: CurrencyCode;
  /** PayPal identifiers exist only after a real sandbox refund. */
  paypalRefundId: string | null;
  failureReason: string | null;
  steps: RefundTimelineStep[];
}

/* ---------- Audit log ---------- */

export type AuditEventType =
  | "return_submitted"
  | "policy_evaluated"
  | "ai_analysis_generated"
  | "review_started"
  | "return_approved"
  | "return_rejected"
  | "refund_initiated"
  | "refund_completed"
  | "refund_failed"
  | "policy_updated";

export type AuditActorType = "customer" | "seller" | "system" | "ai";

export interface AuditEntry {
  id: string;
  /** Related return, or null for account-level events like policy changes. */
  returnId: string | null;
  eventType: AuditEventType;
  actorType: AuditActorType;
  actorName: string;
  /** Short human-readable description. Must not contain secrets or PII. */
  description: string;
  fromStatus: ReturnStatus | null;
  toStatus: ReturnStatus | null;
  occurredAt: string;
}

/* ---------- Settings ---------- */

export interface ReturnPolicy {
  /** Days after delivery during which a return may be requested. */
  returnWindowDays: number;
  requirePaymentCaptured: boolean;
  allowPartialRefunds: boolean;
  /** Amounts above this need manual seller review. */
  manualReviewThreshold: MoneyString;
  currency: CurrencyCode;
  restockingFeePercent: number;
}

/* ---------- Dashboard ---------- */

export interface DashboardMetrics {
  openReturns: number;
  awaitingReview: number;
  refundsPending: number;
  refundedThisMonth: MoneyString;
  currency: CurrencyCode;
  /** Average hours from submission to decision. */
  avgDecisionHours: number;
  returnsByStatus: Record<ReturnStatus, number>;
}